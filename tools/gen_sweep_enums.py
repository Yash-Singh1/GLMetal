#!/usr/bin/env python3
"""Writes sweep_enums.h for tools/apple_enum_sweep.c: every distinct GL enum
value below 0x10000 in the SDK's OpenGL headers (bit masks left out), named
by its first #define.

  gen_sweep_enums.py SDK_OPENGL_HEADERS_DIR OUTPUT
"""
import pathlib
import re
import sys

values = {}
for header in ['gl.h', 'glext.h', 'gl3.h', 'gl3ext.h']:
    text = (pathlib.Path(sys.argv[1]) / header).read_text()
    for name, value in re.findall(r'#define\s+(GL_\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b', text):
        if name.endswith(('_BIT', '_BITS')) or '_BIT_' in name:
            continue
        v = int(value, 0)
        if v <= 0xffff:
            values.setdefault(v, name)
lines = ['/* Generated by tools/gen_sweep_enums.py. */', 'static const struct { unsigned value; const char *name; } sweep_enums[] = {']
lines += [f'    {{{v:#06x}, "{n}"}},' for v, n in sorted(values.items())]
lines += ['};']
pathlib.Path(sys.argv[2]).write_text('\n'.join(lines) + '\n')
